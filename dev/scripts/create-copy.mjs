#!/usr/bin/env node
/**
 * One-command client copy from clients/cemotor.
 *
 *   npm run createCopy -- "Acme Motors"
 *   npm run createCopy -- "Acme Motors" --email owner@acme.com
 *   npm run createCopy -- --name "Acme Motors" --email owner@acme.com --port 5083 --skip-dns
 *
 * Writes clients/{slug}/.env with PLATFORM_TENANT_KEY + handoff secrets,
 * registers Tenant (with key hash), creates shop_uploads/{slug}, optional DNS.
 */
import { config } from "dotenv";
import {
  cpSync,
  existsSync,
  mkdirSync,
  writeFileSync,
  readdirSync,
  readFileSync,
  statSync,
} from "fs";
import { join, resolve } from "path";
import { randomBytes } from "crypto";
import { spawnSync } from "child_process";
import bcrypt from "bcryptjs";
import mongoose from "mongoose";
import { repoRoot, scriptsDir } from "./_paths.mjs";
import { slugifyCustomerName, withDbName, nextClientPort } from "./lib/client-slug.mjs";

config({ path: join(repoRoot, ".env") });

function arg(name, fallback = "") {
  const i = process.argv.indexOf(`--${name}`);
  if (i >= 0 && process.argv[i + 1]) return process.argv[i + 1];
  return fallback;
}
function hasFlag(name) {
  return process.argv.includes(`--${name}`);
}

function devMasterPasswordLine() {
  const fromEnv = String(process.env.DEV_MASTER_PASSWORD || "").trim();
  if (fromEnv.length >= 16) return `DEV_MASTER_PASSWORD=${fromEnv}`;
  const clientsDir = join(repoRoot, "clients");
  if (!existsSync(clientsDir)) return "";
  for (const name of readdirSync(clientsDir)) {
    const envPath = join(clientsDir, name, ".env");
    if (!existsSync(envPath)) continue;
    const match = readFileSync(envPath, "utf8").match(/^DEV_MASTER_PASSWORD=(.+)$/m);
    const value = String(match?.[1] || "").trim();
    if (value.length >= 16) return `DEV_MASTER_PASSWORD=${value}`;
  }
  return "";
}

/** Positional name: everything after -- that is not a flag value pair, or first non-flag argv. */
function positionalName() {
  const named = arg("name") || arg("company") || arg("customer");
  if (named) return named.trim();
  const args = process.argv.slice(2);
  const parts = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a.startsWith("--")) {
      if (!a.includes("=") && args[i + 1] && !args[i + 1].startsWith("--")) i += 1;
      continue;
    }
    parts.push(a);
  }
  return parts.join(" ").trim();
}

function copyDir(src, dst) {
  mkdirSync(dst, { recursive: true });
  for (const name of readdirSync(src)) {
    if (["node_modules", ".next", ".env", ".env.local", ".git"].includes(name)) continue;
    const s = join(src, name);
    const d = join(dst, name);
    if (statSync(s).isDirectory()) copyDir(s, d);
    else cpSync(s, d);
  }
}

const company = positionalName();
if (!company) {
  console.error(`Usage:
  npm run createCopy -- "Customer Name"
  npm run createCopy -- "Customer Name" --email owner@example.com
  npm run createCopy -- --name "Customer Name" --slug acme --email a@b.com --port 5083 --skip-dns`);
  process.exit(1);
}

const slugArg = String(arg("slug")).trim().toLowerCase();
const slug = slugArg || slugifyCustomerName(company);
const ownerEmail = String(arg("email") || arg("owner-email") || "").trim().toLowerCase();
const skipDns = hasFlag("skip-dns");
const from = resolve(arg("from", join(repoRoot, "clients", "cemotor")));
const port = Number(arg("port")) || nextClientPort(repoRoot, { existsSync, readdirSync, readFileSync });

if (!slug || !/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/.test(slug)) {
  console.error("Could not build a valid DNS slug from name. Pass --slug explicitly.");
  process.exit(1);
}

const baseUri = process.env.MONGODB_ADMIN_URI || process.env.MONGODB_URI || "";
if (!baseUri) {
  console.error("Root .env MONGODB_URI required");
  process.exit(1);
}

const dest = join(repoRoot, "clients", slug);
const mongoDbName = `3pf_${slug.replace(/-/g, "_")}`;
const host = `${slug}.3phaseflow.com`;
const uploadsDir = join(repoRoot, "shop_uploads", slug);

if (existsSync(dest)) {
  console.error(`clients/${slug} already exists. Choose another name or --slug.`);
  process.exit(1);
}
if (!existsSync(from)) {
  console.error("Template missing:", from);
  process.exit(1);
}

console.log(`createCopy → clients/${slug}`);
console.log({ company, slug, ownerEmail: ownerEmail || "(none)", port, host });

copyDir(from, dest);
mkdirSync(uploadsDir, { recursive: true });
writeFileSync(join(uploadsDir, ".gitkeep"), "");

const tenantKey = `3pf_${randomBytes(24).toString("base64url")}`;
const handoffSecret = randomBytes(32).toString("hex");
const jwtSecret = randomBytes(32).toString("hex");
const keyHash = await bcrypt.hash(tenantKey, 10);
const clientMongoUri = withDbName(baseUri, mongoDbName);
const platformApiBase =
  process.env.PLATFORM_API_BASE_DEFAULT ||
  process.env.PLATFORM_API_BASE ||
  "http://localhost:5080";

const envBody = `# Generated by createCopy for ${company}
APP_ROLE=client
TENANT_SLUG=${slug}
TENANT_HOST=${host}
TENANT_OWNER_EMAIL=${ownerEmail}
COMPANY_NAME=${company.replace(/"/g, "")}
MONGODB_URI=${clientMongoUri}
NEXT_PUBLIC_SITE_URL=https://${host}
JWT_SECRET=${jwtSecret}
PORT=${port}
SHOP_UPLOADS_ROOT=${uploadsDir}
PLATFORM_API_BASE=${platformApiBase}
PLATFORM_TENANT_KEY=${tenantKey}
SUPPORT_HANDOFF_SECRET=${handoffSecret}
PLATFORM_WEBHOOK_SECRET=${handoffSecret}
FORCE_SHOP_SMTP_ONLY=1
ALLOWED_HOSTS=${host},localhost,127.0.0.1
${devMasterPasswordLine()}
`;

writeFileSync(join(dest, ".env"), envBody);
writeFileSync(
  join(dest, ".env.example"),
  `# clients/${slug}
APP_ROLE=client
TENANT_SLUG=${slug}
TENANT_HOST=${host}
TENANT_OWNER_EMAIL=
MONGODB_URI=
NEXT_PUBLIC_SITE_URL=https://${host}
SHOP_UPLOADS_ROOT=
FORCE_SHOP_SMTP_ONLY=1
ALLOWED_HOSTS=${host},localhost,127.0.0.1
JWT_SECRET=
PLATFORM_API_BASE=http://localhost:5080
PLATFORM_TENANT_KEY=
SUPPORT_HANDOFF_SECRET=
PLATFORM_WEBHOOK_SECRET=

# Local next dev only. Leave empty. Never set this on the server.
DEV_MASTER_PASSWORD=
`
);

const pkgPath = join(dest, "package.json");
if (existsSync(pkgPath)) {
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  pkg.name = `3pf-${slug}`;
  pkg.scripts = {
    dev: `next dev --hostname 0.0.0.0 -p ${port}`,
    build: "next build",
    start: `next start -p ${port}`,
    lint: "eslint",
  };
  writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
}

const webConfigPath = join(dest, "web.config");
const webConfig = `<?xml version="1.0" encoding="UTF-8"?>
<configuration>
  <system.web>
    <customErrors mode="Off" />
    <pages validateRequest="false" />
    <httpRuntime requestPathInvalidCharacters="" requestValidationMode="2.0" />
  </system.web>
  <system.webServer>
    <rewrite>
      <rules>
        <rule name="Redirect to https" stopProcessing="true">
          <match url=".*" />
          <conditions>
            <add input="{HTTPS}" pattern="off" ignoreCase="true" />
          </conditions>
          <action type="Redirect" url="https://{HTTP_HOST}{REQUEST_URI}" redirectType="Permanent" appendQueryString="false" />
        </rule>
        <rule name="ReverseProxyToShop" stopProcessing="true">
          <match url="(.*)" />
          <action type="Rewrite" url="http://localhost:${port}/{R:1}" />
        </rule>
      </rules>
    </rewrite>
  </system.webServer>
</configuration>
`;
writeFileSync(webConfigPath, webConfig);

await mongoose.connect(baseUri);
await mongoose.connection.collection("tenants").updateOne(
  { slug },
  {
    $set: {
      slug,
      host,
      companyName: company,
      ownerEmail,
      mongoDbName,
      codePath: `clients/${slug}`,
      status: "active",
      platformTenantKeyHash: keyHash,
      supportHandoffSecret: handoffSecret,
      webhookUrl: `https://${host}/api/platform/inbound/lead`,
      dnsStatus: skipDns ? "skipped" : "pending",
      port,
      updatedAt: new Date(),
    },
    $setOnInsert: { createdAt: new Date() },
  },
  { upsert: true }
);
if (ownerEmail) {
  await mongoose.connection.collection("listings").updateMany(
    { email: ownerEmail },
    { $set: { tenantSlug: slug } }
  );
}
await mongoose.disconnect();

if (!skipDns) {
  const r = spawnSync(process.execPath, [join(scriptsDir, "dns-upsert.mjs"), "--slug", slug], {
    stdio: "inherit",
    env: process.env,
  });
  if (r.status === 0) {
    await mongoose.connect(baseUri);
    await mongoose.connection.collection("tenants").updateOne({ slug }, { $set: { dnsStatus: "active" } });
    await mongoose.disconnect();
  } else {
    console.warn("DNS upsert failed or skipped; re-run: npm run dns-upsert -- --slug", slug);
  }
}

console.log(`
=== createCopy complete ===
Folder:   clients/${slug}
Database: ${mongoDbName}
Host:     ${host}
Port:     ${port}
.env:     PLATFORM_TENANT_KEY + SUPPORT_HANDOFF_SECRET written
Tenant:   platformTenantKeyHash stored in motors DB

Next:
  cd clients/${slug} && npm install && npm run dev
  # migrate data (optional):
  npm run migrate-shop-data -- --slug ${slug} --owner-email ${ownerEmail || "OWNER@EMAIL"}
`);
