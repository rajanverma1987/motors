#!/usr/bin/env node
/**
 * Provision an isolated client app under clients/{slug}.
 * Default --from clients/cemotor. Does not auto-register IIS (prints checklist).
 *
 * node scripts/provision-client.mjs --slug acme --company "Acme" --owner-email a@b.com --port 5083
 * node scripts/provision-client.mjs --slug cemotor --from-existing clients/cemotor --owner-email cemotorrepair@gmail.com --port 5082
 */
import { config } from "dotenv";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  readdirSync,
  statSync,
  rmSync,
} from "fs";
import { join, resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { randomBytes } from "crypto";
import bcrypt from "bcryptjs";
import mongoose from "mongoose";
import { devRoot, repoRoot } from "./_paths.mjs";

const root = repoRoot;
const appRoot = devRoot;
config({ path: join(root, ".env") });

function arg(name, fallback = "") {
  const i = process.argv.indexOf(`--${name}`);
  if (i >= 0 && process.argv[i + 1]) return process.argv[i + 1];
  return fallback;
}
function hasFlag(name) {
  return process.argv.includes(`--${name}`);
}

const slug = String(arg("slug")).trim().toLowerCase();
const company = arg("company", slug);
const ownerEmail = String(arg("owner-email")).trim().toLowerCase();
const port = Number(arg("port", "5083"));
const fromExisting = arg("from-existing");
const from = arg("from", join(root, "clients", "cemotor"));
const skipDns = hasFlag("skip-dns");

if (!slug || !/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/.test(slug)) {
  console.error("Valid --slug required (DNS-safe)");
  process.exit(1);
}

const dest = join(root, "clients", slug);
const mongoDbName = `3pf_${slug.replace(/-/g, "_")}`;
const host = `${slug}.3phaseflow.com`;
const uploadsDir = join(root, "shop_uploads", slug);

function copyDir(src, dst) {
  mkdirSync(dst, { recursive: true });
  for (const name of readdirSync(src)) {
    if (["node_modules", ".next", ".env", ".git"].includes(name)) continue;
    const s = join(src, name);
    const d = join(dst, name);
    if (statSync(s).isDirectory()) copyDir(s, d);
    else cpSync(s, d);
  }
}

console.log(`Provisioning ${slug}…`);

if (fromExisting) {
  const existing = resolve(root, fromExisting);
  if (!existsSync(existing)) {
    console.error("from-existing path missing:", existing);
    process.exit(1);
  }
  if (resolve(existing) !== resolve(dest)) {
    console.error("--from-existing must point at clients/{slug} when wiring an already-extracted tree");
    process.exit(1);
  }
  console.log("Using existing tree", dest);
} else {
  if (existsSync(dest)) {
    console.error("clients/" + slug + " already exists");
    process.exit(1);
  }
  const src = resolve(from);
  if (!existsSync(src)) {
    console.error("Copy source missing:", src);
    process.exit(1);
  }
  copyDir(src, dest);
  console.log("Copied", src, "→", dest);
}

mkdirSync(uploadsDir, { recursive: true });
writeFileSync(join(uploadsDir, ".gitkeep"), "");

const tenantKey = `3pf_${randomBytes(24).toString("base64url")}`;
const handoffSecret = randomBytes(32).toString("hex");
const jwtSecret = randomBytes(32).toString("hex");
const keyHash = await bcrypt.hash(tenantKey, 10);

const baseUri = process.env.MONGODB_ADMIN_URI || process.env.MONGODB_URI || "";
if (!baseUri) {
  console.error("MONGODB_URI or MONGODB_ADMIN_URI required");
  process.exit(1);
}

function withDbName(uri, dbName) {
  try {
    const u = new URL(uri);
    u.pathname = `/${dbName}`;
    return u.toString();
  } catch {
    if (uri.includes("?")) {
      const [pre, q] = uri.split("?");
      const base = pre.replace(/\/?$/, "");
      const noDb = base.replace(/\/[^/]+$/, "");
      return `${noDb}/${dbName}?${q}`;
    }
    return `${uri.replace(/\/?$/, "")}/${dbName}`;
  }
}

const clientMongoUri = withDbName(baseUri, mongoDbName);

const envBody = `# Generated by provision-client for ${slug}
APP_ROLE=client
TENANT_SLUG=${slug}
TENANT_HOST=${host}
TENANT_OWNER_EMAIL=${ownerEmail}
COMPANY_NAME=${company.replace(/"/g, "")}
MONGODB_URI=${clientMongoUri}
NEXT_PUBLIC_SITE_URL=https://${host}
JWT_SECRET=${jwtSecret}
PORT=${port}
SHOP_UPLOADS_ROOT=${uploadsDir}
PLATFORM_API_BASE=https://admin.3phaseflow.com
PLATFORM_TENANT_KEY=${tenantKey}
SUPPORT_HANDOFF_SECRET=${handoffSecret}
PLATFORM_WEBHOOK_SECRET=${handoffSecret}
FORCE_SHOP_SMTP_ONLY=1
ALLOWED_HOSTS=${host},localhost,127.0.0.1
`;

writeFileSync(join(dest, ".env"), envBody);
console.log("Wrote", join(dest, ".env"));

// Register tenant in platform DB (same cluster, original DB name from MONGODB_URI)
await mongoose.connect(baseUri);
const tenants = mongoose.connection.collection("tenants");
await tenants.updateOne(
  { slug },
  {
    $set: {
      slug,
      host,
      companyName: company,
      ownerEmail,
      mongoDbName,
      codePath: `clients/${slug}`,
      status: "active",
      platformTenantKeyHash: keyHash,
      supportHandoffSecret: handoffSecret,
      webhookUrl: `https://${host}/api/platform/inbound/lead`,
      dnsStatus: skipDns ? "skipped" : "pending",
      port,
      updatedAt: new Date(),
    },
    $setOnInsert: { createdAt: new Date() },
  },
  { upsert: true }
);
if (ownerEmail) {
  await mongoose.connection.collection("listings").updateMany(
    { email: ownerEmail },
    { $set: { tenantSlug: slug } }
  );
}
await mongoose.disconnect();
console.log("Tenant registry updated");

if (!skipDns) {
  const { spawnSync } = await import("child_process");
  const r = spawnSync(process.execPath, [join(appRoot, "scripts", "dns-upsert.mjs"), "--slug", slug], {
    stdio: "inherit",
    env: process.env,
  });
  if (r.status === 0) {
    await mongoose.connect(baseUri);
    await mongoose.connection.collection("tenants").updateOne({ slug }, { $set: { dnsStatus: "active" } });
    await mongoose.disconnect();
  } else {
    console.warn("DNS upsert failed; set dns manually or re-run with credentials");
  }
}

console.log(`
=== IIS / SSL checklist (you perform) ===
1. Bind hostname ${host} to port ${port} (or reverse-proxy to 127.0.0.1:${port})
2. Issue SSL certificate for ${host} on the server
3. cd clients/${slug} && npm install && npm run build && npm run start
4. Smoke: https://${host}/login
5. PLATFORM_TENANT_KEY is in clients/${slug}/.env (keep secret)
`);
