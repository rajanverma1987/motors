const BY_ID = new Map(WINDOWS_TIME_ZONES.map((zone) => [zone.id.toLowerCase(), zone]));
const BY_IANA = new Map();
for (const zone of WINDOWS_TIME_ZONES) {
  const key = zone.iana.toLowerCase();
  if (!BY_IANA.has(key)) BY_IANA.set(key, zone);
}

/** Stored shop timezone is a Windows time zone id. Also accepts a previously saved IANA name. */
export function normalizeShopTimeZone(value) {
  const raw = String(value || "").trim();
  if (!raw || raw.length > 80) return "";
  const byId = BY_ID.get(raw.toLowerCase());
  if (byId) return byId.id;
  const byIana = BY_IANA.get(raw.toLowerCase());
  if (byIana) return byIana.id;
  return "";
}

/** IANA zone used to format payroll dates and clock times. */
export function ianaTimeZoneForShop(value) {
  const id = normalizeShopTimeZone(value);
  if (!id) return "";
  return BY_ID.get(id.toLowerCase())?.iana || "";
}

export function windowsTimeZoneLabel(value) {
  const id = normalizeShopTimeZone(value);
  if (!id) return "";
  return BY_ID.get(id.toLowerCase())?.label || "";
}

export function windowsTimeZoneOptions() {
  return WINDOWS_TIME_ZONES.map((zone) => ({ value: zone.id, label: zone.label }));
}
